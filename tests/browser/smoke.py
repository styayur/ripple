"""Browser verification of the real view code hosted by a mocked SDK, not Obsidian."""
import json
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

root = Path(__file__).resolve().parents[2]
output = root / 'reports' / 'browser'
checks = []
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width': 400, 'height': 1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto((output / 'index.html').as_uri())
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('status')).to_contain_text('3 / 3')
    slider = page.get_by_role('slider', name='Relevance threshold percent')
    expect(slider).to_be_disabled()
    checks.append('Empty query preserves all candidates and disables slider')
    query = page.get_by_role('textbox', name='Graph filter query')
    query.fill('Ocean')
    expect(slider).to_be_enabled()
    slider.fill('100')
    expect(page.get_by_role('status')).to_contain_text('1 / 3')
    ocean_circle = page.locator('.ripple-plot circle').filter(has=page.locator('title').filter(has_text=re.compile('^Ocean$')))
    position = ocean_circle.evaluate('(el) => [el.getAttribute("cx"), el.getAttribute("cy")]')
    slider.fill('0')
    expect(page.get_by_role('status')).to_contain_text('3 / 3')
    assert position == ocean_circle.evaluate('(el) => [el.getAttribute("cx"), el.getAttribute("cy")]')
    checks.append('0/100 thresholds update counts without moving original preview nodes')
    query.fill('"unclosed')
    expect(page.get_by_role('alert')).to_contain_text('Close the quoted phrase')
    expect(page.get_by_role('status')).to_contain_text('3 / 3')
    checks.append('Parse errors preserve last successful visibility')
    page.get_by_role('button', name='Clear and restore').click()
    expect(query).to_have_value('')
    expect(page.get_by_role('status')).to_contain_text('Original graph')
    checks.append('Clear restores original state')
    query.fill('unfindable')
    slider.fill('100')
    expect(page.get_by_role('status')).to_contain_text('0 / 3')
    expect(page.get_by_text('No matches at this threshold.', exact=False)).to_be_visible()
    checks.append('Empty result has actionable guidance')
    page.get_by_role('button', name='Clear and restore').click()
    page.get_by_role('combobox', name='Graph source', exact=True).select_option('graphfrontier')
    expect(page.get_by_role('status')).to_contain_text('3 / 3')
    expect(page.get_by_role('checkbox')).to_be_disabled()
    calls = page.evaluate('window.rippleFixture.calls')
    assert all(call['readOnly'] and call['method'] in ['listViews', 'getState', 'getGraph'] for call in calls)
    checks.append('GraphFrontier mock snapshot is read-only and visibly scoped to preview')
    page.evaluate('window.rippleFixture.invalidate()')
    expect(page.get_by_role('alert')).to_contain_text('Vault changed')
    query.fill('Ocean')
    expect(page.get_by_role('status')).to_contain_text('1 / 3')
    expect(page.get_by_role('alert')).to_contain_text('Vault changed')
    page.get_by_role('button', name='Clear and restore').click()
    page.get_by_role('button', name='Refresh graph').click()
    expect(page.get_by_role('status')).to_contain_text('3 / 3')
    checks.append('Invalidation reports stale snapshot and refresh recovers')
    page.screenshot(path=str(output / 'light.png'), full_page=True)
    page.evaluate('document.body.classList.add("dark")')
    page.screenshot(path=str(output / 'dark.png'), full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    checks.append('Light/dark 400px layout has no horizontal overflow')
    page.evaluate('window.rippleFixture.close()')
    assert page.evaluate('[...window.rippleFixture.handlers.values()].every(set => set.size === 0)')
    page.evaluate('window.rippleFixture.mount()')
    expect(page.get_by_role('status')).to_contain_text('3 / 3')
    checks.append('Close releases event subscriptions; re-enable creates a working session')
    page.evaluate('window.rippleFixture.app.vault.getMarkdownFiles = () => []')
    page.get_by_role('button', name='Refresh graph').click()
    expect(page.get_by_role('status')).to_contain_text('0 / 0')
    checks.append('Empty vault renders normally')
    assert not errors, errors
    browser.close()
(output / 'results.json').write_text(json.dumps({'environment': 'Chromium headless + mocked Obsidian SDK', 'checks': checks, 'pageErrors': errors}, indent=2), encoding='utf-8')
print(json.dumps({'passed': len(checks), 'checks': checks}, indent=2))
